#!/usr/bin/env node
// Writes src/shared/tlds.ts: the top-level domains of the Public Suffix List's ICANN section,
// in Unicode and in punycode. The embedded browser's address field opens text whose host
// ends in one of them and searches for anything else, as Chrome does.
//   node scripts/update-tlds.mjs [path-to-public_suffix_list.dat]
// Without a path it reads https://publicsuffix.org/list/public_suffix_list.dat.
import fs from "node:fs";
import path from "node:path";
import { domainToASCII } from "node:url";

const desktop = path.resolve(import.meta.dirname, "..");
const out = path.join(desktop, "src/shared/tlds.ts");
const source = process.argv[2];
const text = source ? fs.readFileSync(source, "utf8") : await (await fetch("https://publicsuffix.org/list/public_suffix_list.dat")).text();

const start = text.indexOf("===BEGIN ICANN DOMAINS===");
const end = text.indexOf("===END ICANN DOMAINS===");
if (start < 0 || end < start) throw new Error("not the Public Suffix List: no ICANN section");
const tlds = new Set();
for (const raw of text.slice(start, end).split("\n")) {
  const line = raw.trim();
  if (!line || line.startsWith("//") || line.includes(".")) continue;
  const tld = line.replace(/^[!*]/, "").toLowerCase();
  tlds.add(tld);
  const ascii = domainToASCII(tld);
  if (ascii && ascii !== tld) tlds.add(ascii);
}
if (tlds.size < 1000) throw new Error(`only ${tlds.size} top-level domains: the list looks wrong`);
const list = [...tlds].sort();
fs.writeFileSync(
  out,
  `// Generated by scripts/update-tlds.mjs from the Public Suffix List (https://publicsuffix.org,\n` +
    `// Mozilla Public License 2.0); do not edit. The top-level domains of its ICANN section.\n\n` +
    `export const topLevelDomains: ReadonlySet<string> = new Set(\n  ${JSON.stringify(list.join(" "))}.split(" "),\n);\n`,
);
console.log(`wrote ${path.relative(desktop, out)}: ${list.length} top-level domains`);
